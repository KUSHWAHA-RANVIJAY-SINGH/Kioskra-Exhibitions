const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

// Paths relative to project root
const ROOT_DIR = path.resolve(__dirname, '..');
const INPUT_DIR = path.join(ROOT_DIR, 'raw-portfolio-images');
const OUTPUT_DIR = path.join(ROOT_DIR, 'public', 'private-gallery');
const DATA_FILE_PATH = path.join(ROOT_DIR, 'lib', 'privateGalleryData.ts');

async function processImages() {
  try {
    console.log('🚀 Starting portfolio image optimization script...');

    // 1. Ensure input directory exists
    if (!fs.existsSync(INPUT_DIR)) {
      throw new Error(`Input directory not found at: ${INPUT_DIR}`);
    }

    // 2. Ensure output directories exist
    if (!fs.existsSync(OUTPUT_DIR)) {
      fs.mkdirSync(OUTPUT_DIR, { recursive: true });
      console.log(`📁 Created output directory: ${OUTPUT_DIR}`);
    }

    const libDir = path.dirname(DATA_FILE_PATH);
    if (!fs.existsSync(libDir)) {
      fs.mkdirSync(libDir, { recursive: true });
    }

    // 3. Read and sort .jpg files naturally
    const files = fs.readdirSync(INPUT_DIR)
      .filter(file => file.toLowerCase().endsWith('.jpg') || file.toLowerCase().endsWith('.jpeg'))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

    console.log(`📸 Found ${files.length} images to process in ${INPUT_DIR}`);

    const imagePaths = [];
    let processedCount = 0;

    // 4. Process each image sequentially
    for (let i = 0; i < files.length; i++) {
      const fileName = files[i];
      const inputPath = path.join(INPUT_DIR, fileName);
      const outputFileName = `stall-${i + 1}.webp`;
      const outputPath = path.join(OUTPUT_DIR, outputFileName);
      const webPath = `/private-gallery/${outputFileName}`;

      const imagePipeline = sharp(inputPath);
      const metadata = await imagePipeline.metadata();

      let resizedPipeline = sharp(inputPath);

      // Resize if width > 1200px maintaining aspect ratio
      if (metadata.width && metadata.width > 1200) {
        resizedPipeline = resizedPipeline.resize({
          width: 1200,
          withoutEnlargement: true
        });
      }

      // Convert to webp with quality 80
      await resizedPipeline
        .webp({ quality: 80 })
        .toFile(outputPath);

      const stats = fs.statSync(outputPath);
      const sizeKB = (stats.size / 1024).toFixed(1);

      imagePaths.push(webPath);
      processedCount++;

      console.log(`[${processedCount}/${files.length}] Processed ${fileName} -> ${outputFileName} (${sizeKB} KB)`);
    }

    // 5. Generate TypeScript file exporting the image paths array
    const tsContent = `// Auto-generated by scripts/optimize-portfolio.js
// Do not edit directly

export const privateGalleryImages: string[] = ${JSON.stringify(imagePaths, null, 2)};
`;

    fs.writeFileSync(DATA_FILE_PATH, tsContent, 'utf-8');
    console.log(`\n✅ Generated TypeScript data file at: ${DATA_FILE_PATH}`);
    console.log(`🎉 Optimization complete! Successfully processed ${processedCount} images into ${OUTPUT_DIR}`);

  } catch (error) {
    console.error('❌ Error processing images:', error);
    process.exit(1);
  }
}

processImages();
